let lang = 'en';
export const getLang = () => lang;
export const locale = () => LOCALES[lang];
export function setLang(code) {
  if (LANGS.includes(code)) lang = code;
  document.documentElement.lang = lang;
  try { localStorage.setItem('marione-lang', lang); } catch { /* storage blocked */ }
}
/** Before the server answers: the last choice on this device, else the browser's language, else English. */
export function initialLang() {
  let saved = null;
  try { saved = localStorage.getItem('marione-lang'); } catch { /* storage blocked */ }
  if (LANGS.includes(saved)) return saved;
  for (const l of navigator.languages || [navigator.language || 'en']) {
    const short = String(l).slice(0, 2).toLowerCase();
    if (LANGS.includes(short)) return short;
  }
  return 'en';
}

export function t(key, vars) {
  const row = T[key];
  let text = row ? row[LANGS.indexOf(lang)] || row[0] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split('{' + k + '}').join(String(v));
  return text;
}

